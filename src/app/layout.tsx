import type { Metadata } from "next";
import { Geist, Geist_Mono, JetBrains_Mono, Battambang, Playfair_Display } from "next/font/google";
import "./globals.css";
import { cn } from "@/lib/utils";
import {NextIntlClientProvider} from 'next-intl';
import {Suspense} from 'react';
import {LangSync} from '@/components/lang-sync';

const jetbrainsMono = JetBrains_Mono({subsets:['latin'],variable:'--font-mono'});

// Khmer glyphs for text the Latin fonts cannot draw
const battambang = Battambang({subsets:["khmer"],weight:["100","300","400","700","900"],variable:"--font-khmer"});

const playfair = Playfair_Display({subsets:['latin'],variable:'--font-serif'});

const geistSans = Geist({
    variable: "--font-geist-sans",
    subsets: ["latin"],
});

const geistMono = Geist_Mono({
    variable: "--font-geist-mono",
    subsets: ["latin"],
});

export const metadata: Metadata = {
    title: { template: "Blue Gym - %s", default: "Blue Gym" },
    description: "Generated by create next app",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
    return (
        <html lang="en" suppressHydrationWarning className={cn(geistSans.variable, geistMono.variable, "font-mono", jetbrainsMono.variable, playfair.variable, battambang.variable)}>
            <head>
                <script
                    dangerouslySetInnerHTML={{
                        __html: `try{var t=localStorage.getItem("theme")||"system";if(t==="dark"||(t==="system"&&matchMedia("(prefers-color-scheme: dark)").matches))document.documentElement.classList.add("dark")}catch(e){}`,
                    }}
                />
            </head>
            <body>
                <Suspense fallback={null}>
                    <NextIntlClientProvider>
                        <LangSync />
                        {children}
                    </NextIntlClientProvider>
                </Suspense>
            </body>
        </html>
    );
}
